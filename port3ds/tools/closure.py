#!/usr/bin/env python3
"""Grow a 3DS smoke target until its link closes, using the decomp's own
naming rule: a src/ file is named after the symbol it defines (or carries an
`@symbol <name>` tag when it was merged into a translation unit).

  closure.py <target> [--max-rounds N]

Each round builds <target>, reads build3ds/<target>_linkfix.txt for symbols
that are still undefined, finds the src/ files that define them, and appends
those (relative to PORT_ROOT) to port3ds/slices/<target>.auto.txt, which the
CMake target reads. Stops when a round adds nothing.
"""
import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
P3DS = os.path.dirname(HERE)
ROOT = os.path.dirname(P3DS)
PORT_ROOT = os.path.join(ROOT, 'port-0.9.1')
BUILD = os.path.join(ROOT, 'build3ds')
BASH = r'C:\devkitPro\msys2\usr\bin\bash.exe'

TAG = re.compile(r'@symbol\s+(\S+)')


def index_src():
    idx = {}
    src = os.path.join(PORT_ROOT, 'src')
    for root, _, files in os.walk(src):
        for f in files:
            if not f.endswith(('.c', '.cpp')):
                continue
            path = os.path.join(root, f)
            rel = os.path.relpath(path, PORT_ROOT).replace('\\', '/')
            stem = f.rsplit('.', 1)[0]
            idx.setdefault(stem, rel)
            try:
                with open(path, encoding='utf-8', errors='replace') as fh:
                    head = fh.read()
            except OSError:
                continue
            for m in TAG.finditer(head):
                idx.setdefault(m.group(1), rel)
    return idx


HOSTGEN = os.path.join(PORT_ROOT, 'port', 'tools', 'hostgen.py')
PROBE = os.path.join(BUILD, 'hostgen-probe')


def _body(lines):
    """Source lines without hostgen's banner/#include and the //cpp marker."""
    out = []
    for l in lines:
        s = l.strip()
        if s == '//cpp' or s.startswith('// GENERATED by tools/hostgen.py') \
                or s.startswith('// Do not edit. The source of truth') \
                or s.startswith('// transform or the host I/O layer') \
                or s == '#include "ntr/mmio.h"':
            continue
        out.append(l.rstrip())
    while out and not out[0]:
        out.pop(0)
    return out


def needs_hostgen(rel):
    """True when port/tools/hostgen.py changes this src/ file beyond its
    banner: an MMIO proxy, or one of its ABI patch rows (REG_RIDE_ARG,
    VIRTUAL_CALL, ARG_WIDTH, ...). Such a file must be compiled from the
    rewritten copy, as the PC build does, or write-triggered registers only
    latch and register-riding arguments arrive as garbage."""
    if not rel.startswith('src/') or rel.count('/') != 1:
        return False      # hostgen addresses top-level src/<symbol>.c(pp) files
    sym = rel[4:].rsplit('.', 1)[0]
    r = subprocess.run([sys.executable, '-I', HOSTGEN, '--out', PROBE, sym],
                       capture_output=True, text=True)
    gen = os.path.join(PROBE, 'src', sym + '.cpp')
    if r.returncode != 0 or not os.path.exists(gen):
        return False
    orig = open(os.path.join(PORT_ROOT, rel), encoding='utf-8', errors='replace').read().splitlines()
    new = open(gen, encoding='utf-8', errors='replace').read().splitlines()
    return _body(orig) != _body(new)


def build(target):
    env = dict(os.environ, MSYSTEM='MSYS')
    # <target>_3dsx depends on the ELF, so this also refreshes the .3dsx.
    r = subprocess.run([BASH, '-l', '/c/sm64ds-3ds/port3ds/build.sh', '--target',
                        target + '_3dsx', '--', '-k', '0'], env=env, capture_output=True, text=True)
    return r.returncode == 0, r.stdout + r.stderr


def missing(target):
    path = os.path.join(BUILD, '%s_linkfix.txt' % target)
    """[(symbol, referenced_by_game_code)]"""
    out = []
    if not os.path.exists(path):
        return out
    for line in open(path):
        if line.startswith('missing '):
            parts = line.split()
            out.append((parts[1], len(parts) > 2 and parts[2] == '(game)'))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('target')
    ap.add_argument('--max-rounds', type=int, default=12)
    a = ap.parse_args()

    idx = index_src()
    auto = os.path.join(P3DS, 'slices', '%s.auto.txt' % a.target)
    os.makedirs(os.path.dirname(auto), exist_ok=True)
    have = set()
    if os.path.exists(auto):
        have = {l.strip() for l in open(auto) if l.strip() and not l.startswith('#')}
        # a hostgen:<sym> entry stands for src/<sym>.c(pp) too
        for e in list(have):
            if e.startswith('hostgen:'):
                for ext in ('.c', '.cpp'):
                    have.add('src/' + e[8:] + ext)

    for rnd in range(1, a.max_rounds + 1):
        ok, log = build(a.target)
        # Names the runtime libraries provide are not the game's to supply.
        libcache = os.path.join(BUILD, 'libsyms.txt')
        libsyms = set(open(libcache).read().split()) if os.path.exists(libcache) else set()
        need = []
        for sym, from_game in missing(a.target):
            # A runtime-library name is the game's to supply only when game
            # code asks for it (linkfix then keeps it private to the game).
            if sym in libsyms and not from_game:
                continue
            rel = idx.get(sym)
            if rel and rel not in have:
                need.append((sym, rel))
        if ok and not need:
            print('round %d: %s links' % (rnd, a.target))
            return 0
        if not need:
            print('round %d: link fails and nothing more is found in src/' % rnd)
            errs = [l for l in log.splitlines() if 'undefined reference' in l or 'error:' in l]
            print('\n'.join(errs[-40:]))
            return 1
        with open(auto, 'a') as f:
            if not have:
                f.write('# generated by port3ds/tools/closure.py: src/ files pulled in to\n'
                        '# close the link of this target. Paths relative to PORT_ROOT.\n')
            for sym, rel in sorted(set(need), key=lambda x: x[1]):
                if rel in have:
                    continue
                entry = rel
                if needs_hostgen(rel):
                    entry = 'hostgen:' + rel[4:].rsplit('.', 1)[0]
                f.write('%s\n' % entry)
                have.add(rel)
                have.add(entry)
                print('round %d: + %-70s (%s)' % (rnd, entry, sym))
    print('gave up after %d rounds' % a.max_rounds)
    return 1


if __name__ == '__main__':
    sys.exit(main())
